#!/usr/bin/env node
/**
 * gen-nearfg-sprites.mjs — near-foreground road-prop sprites (ADR-0047, amended
 * by the road-props gptimage remake — see docs/handoffs/tech-plan-road-props.md).
 *
 * Generates the 8 near-foreground décor props via the shared gptimage-large
 * pipeline (scripts/lib/gptimage.mjs): magenta chroma-key ground, chroma-keyed
 * + luma-desaturated to strict GREY (house law C1 — décor carries ZERO colour).
 * Sizes are NON-SQUARE per kind (height 512, width = round(512 * aspect), see
 * `nearForegroundArt.types.<kind>.size` in levelArt.json — the JSON already
 * carries the pre-computed width; this script reads it, it does not recompute
 * it). Non-square generation follows scripts/lib/gptimage.mjs's documented
 * approach: request a SQUARE gptimage-large render, then chroma-key + center-
 * crop to the kind's aspect BEFORE the final downscale (`keyAndDown`).
 *
 * Single source of truth: the `nearForegroundArt` block of
 * src/game/levels/levelArt.json (opening/style/per-kind prompt/seed/asset/size).
 * Add or tune a prop THERE, never here.
 *
 * The trafficLight PNG is a DEAD-lens grey housing ONLY — the coloured lit lens
 * + halo is a render-side overlay driven by the `lenses` anchors (the one
 * directed C1 exception, see the block's $comment); this generator has no
 * special case for it beyond generating its housing like every other kind.
 *
 * gptimage-large is a PREMIUM Pollinations model (spends Pollen) — this
 * normally runs in CI only (.github/workflows/gen-nearfg-sprites.yml), never
 * locally without a POLLINATIONS_TOKEN (see readToken() in the lib).
 *
 * Only MISSING files are generated by default (cheap re-runs); FORCE=1
 * regenerates every kind. A kind whose `prompt` is still the pre-gate empty
 * placeholder ("") is SKIPPED with a loud warning — never spends Pollen on an
 * empty prompt (see levelArt.json's `nearForegroundArt.$comment` for gate
 * status; scripts/check-art-prompts.mjs's nearForeground set mirrors this same
 * tolerate-but-warn rule).
 *
 * Usage:
 *   node scripts/gen-nearfg-sprites.mjs                # generate missing (network)
 *   FORCE=1 node scripts/gen-nearfg-sprites.mjs         # regenerate all (network) [CI]
 *   node scripts/gen-nearfg-sprites.mjs --asset bollard # one kind only
 *   node scripts/gen-nearfg-sprites.mjs --list          # list defined kinds
 *
 * `--plan <id>` (SP2 phase (d), T5) — additive path: instead of levelArt.json's
 * `nearForegroundArt.types`, iterates the plan's `props[]`
 * (`src/game/levels/generated/<id>.ts`, `scripts/lib/loadPlan.mjs`) and writes
 * each one to `public/assets/nearfg/<id>/<name>.png` — the exact path
 * `GeneratedPropSpec.asset` declares (`assets/nearfg/<id>/<name>.png`, relative
 * to `public/`), so the namespace lives in the OUTPUT PATH, not just the prop's
 * `kind`. The shared `nearForegroundArt.opening`/`style` from levelArt.json are
 * still reused (house décor look) — only the per-prop prompt is plan-derived
 * (its kind's name segment, after the `<id>:` namespace). Every downstream gate
 * (`check-nearfg-style.mjs`) reads the PNG on disk, so it applies unchanged.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath, pathToFileURL } from "url";
import { readToken, genUrl, withRetry, keyAndDown, cyanPreviewCanvas } from "./lib/gptimage.mjs";
import { sleep } from "./lib/pollinations.mjs";
import { skip } from "./lib/idempotent.mjs";
import { parseAssetArgs } from "./lib/cli.mjs";
import { loadPlan, planIdFromArgs } from "./lib/loadPlan.mjs";
import { promptDescriptor } from "./lib/planNamespace.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const OUT_DIR = path.resolve(ROOT, process.env.OUT_DIR ?? "public/assets/nearfg");
// LEVEL_ART env override mirrors check-art-prompts.mjs/check-sprite-style.mjs —
// handy for fixtures/tests.
const LEVEL_ART = path.resolve(ROOT, process.env.LEVEL_ART ?? "src/game/levels/levelArt.json");
const FORCE = process.env.FORCE === "1";
const GEN = parseInt(process.env.GEN ?? "1024", 10);
const TOL = parseInt(process.env.TOL ?? "95", 10);

/**
 * loadNearForegroundArt() -> [{ kind, prompt, assembled, width, height, seed, asset }]
 * Pure read of the `nearForegroundArt` block — no network, no generation.
 */
export function loadNearForegroundArt() {
  const json = JSON.parse(fs.readFileSync(LEVEL_ART, "utf8"));
  const block = json.nearForegroundArt;
  if (!block || !block.types) {
    throw new Error(`No "nearForegroundArt.types" block in ${path.relative(ROOT, LEVEL_ART)}`);
  }
  const opening = block.opening ?? "";
  const style = block.style ?? "";
  return Object.entries(block.types).map(([kind, def]) => {
    const prompt = typeof def.prompt === "string" ? def.prompt : "";
    const width = def.size?.width;
    const height = def.size?.height;
    // A missing/malformed `size` silently defaulting to 256x512 would generate
    // a distorted, mis-cropped texture for that kind. check-art-prompts.mjs
    // already errors on this in CI, but the generator must be honest run
    // standalone too — fail loudly rather than shipping a wrong-aspect PNG.
    if (!Number.isInteger(width) || width <= 0 || !Number.isInteger(height) || height <= 0) {
      throw new Error(
        `nearForegroundArt.types.${kind}.size — missing/invalid width/height ` +
          `(got ${JSON.stringify(def.size)}); see levelArt.json`,
      );
    }
    const asset = def.asset ?? `assets/nearfg/${kind}.png`;
    return {
      kind,
      prompt,
      assembled: `${opening}${prompt}${style}`,
      width,
      height,
      // Pinned seed → reproducible rolls, reviewable diffs (REROLL=1 ignores it).
      seed: Number.isInteger(def.seed) && process.env.REROLL !== "1" ? def.seed : null,
      asset,
      // Kept identical to today's byte-for-byte behaviour (`${OUT_DIR}/${kind}.png`)
      // — `loadNearForegroundArtFromPlan` below is the one path whose `outFile`
      // genuinely differs (a plan's kind contains a ":" namespace prefix, unusable
      // as a filename), so main() always reads THIS field rather than
      // recomputing a path from `kind` itself.
      outFile: path.join(OUT_DIR, `${kind}.png`),
    };
  });
}

/**
 * loadNearForegroundArtFromPlan(plan, { opening, style }) -> same shape as
 * loadNearForegroundArt(), one entry per `plan.props[]` (SP2 phase (d), T5).
 * `outFile` is resolved from the prop's OWN declared `asset` path
 * (`assets/nearfg/<id>/<name>.png`, exactly what `GeneratedPropSpec.asset`
 * says — namespace lives in the path, not just `kind`), never recomputed from
 * `kind` (which contains a `<id>:` prefix unusable as a filename). Pure — no
 * fs/network.
 */
export function loadNearForegroundArtFromPlan(plan, { opening = "", style = "" } = {}) {
  const publicRoot = path.resolve(ROOT, "public");
  return plan.props.map((p) => {
    // Shared with gen-enemy-types.mjs — the ONE copy of the namespace-
    // stripping rule (panel run-4 on PR #156).
    const prompt = `a ${promptDescriptor(p.kind, plan.id)}`;
    // This is the first code path that turns a plan's `asset` string into a
    // real filesystem WRITE target: an absolute path makes path.resolve drop
    // the public/ prefix entirely, and a ".."-laden one climbs out of it —
    // either would let malformed plan data write anywhere on the runner
    // (panel run-2 on PR #156). validateLevelPlan enforces the same law at
    // CI time; this containment check is the generator's own last line.
    const outFile = path.resolve(publicRoot, p.asset);
    if (!outFile.startsWith(publicRoot + path.sep)) {
      throw new Error(
        `prop ${p.kind}: asset "${p.asset}" escapes public/ (absolute path or ".." traversal) — ` +
          `expected the documented shape assets/nearfg/<id>/<name>.png`,
      );
    }
    return {
      kind: p.kind,
      prompt,
      assembled: `${opening}${prompt}${style}`,
      width: Math.round(512 * p.aspect),
      height: 512,
      seed: null, // free seed (spec §2.2) — same as the hand-authored table's null path
      asset: p.asset,
      outFile,
    };
  });
}

// Exported for testability (same reason as loadNearForegroundArt): asserts
// the keyAndDown wiring — globalKey MUST stay on for this C1 strict-grey
// family — without spending Pollen on a real network round trip.
export async function generateOne(token, assembledPrompt, seed, width, height) {
  const effectiveSeed = seed ?? Math.floor(Math.random() * 99999);
  const url = genUrl(assembledPrompt, effectiveSeed, { gen: GEN });
  const buf = await withRetry(url, token, 3);
  // luma-desaturation ALWAYS on (keepColor:false) — strict grey décor (C1).
  // globalKey ALWAYS on too: this family is C1 strict-grey (no legit magenta
  // in the art), so it's safe to key every remaining near-magenta pixel, not
  // just flood-fill-connected ones — closes enclosed magenta pockets (e.g.
  // between wheels, under a floorboard) that the edge flood fill can't reach.
  const result = await keyAndDown(buf, {
    targetW: width,
    targetH: height,
    keepColor: false,
    tol: TOL,
    globalKey: true,
  });
  return { ...result, effectiveSeed };
}

/** Resolve the prop list: `--plan <id>` (T5) or the levelArt.json table (default). */
async function resolveProps(args) {
  const levelId = planIdFromArgs(args);
  if (levelId === null) return loadNearForegroundArt();
  const plan = await loadPlan(levelId);
  const json = JSON.parse(fs.readFileSync(LEVEL_ART, "utf8"));
  const opening = json.nearForegroundArt?.opening ?? "";
  const style = json.nearForegroundArt?.style ?? "";
  return loadNearForegroundArtFromPlan(plan, { opening, style });
}

async function main() {
  const args = process.argv.slice(2);
  const props = await resolveProps(args);
  const { list, target } = parseAssetArgs(args);

  if (list) {
    console.log("Defined near-foreground props:");
    props.forEach((p) =>
      console.log(
        `  ${p.kind.padEnd(16)} ${p.width}x${p.height}  → ${p.asset}` +
          (p.prompt.trim() ? "" : "  [EMPTY PROMPT — pre-gate placeholder, generation skips it]"),
      ),
    );
    return;
  }

  const todo = target ? props.filter((p) => p.kind === target) : props;
  if (target && todo.length === 0) {
    console.error(`Near-foreground kind "${target}" not found. Use --list.`);
    process.exit(1);
  }

  fs.mkdirSync(OUT_DIR, { recursive: true });

  // Resolve the token ONCE, up front, but only when there is at least one
  // kind this run will actually attempt to generate (skip-existing and
  // empty-prompt entries never touch the network). A missing token THROWS
  // here — uncaught, propagating to the fatal handler below (non-zero exit,
  // clear message) — instead of failing per-kind inside the try/catch below,
  // which used to swallow it as a misleading "will be generated in CI" and
  // let a token-less FORCE=1 re-dispatch silently no-op (green, nothing
  // regenerated). The per-kind try/catch still exists for transient network
  // failures only.
  const pending = todo.filter(
    (p) => !skip(p.outFile, { force: FORCE, existsSync: fs.existsSync }) && p.prompt.trim(),
  );
  const token = pending.length > 0 ? readToken() : null;

  console.log(`Near-foreground sprites → ${path.relative(ROOT, OUT_DIR)}\n`);

  for (const p of todo) {
    const out = p.outFile;
    fs.mkdirSync(path.dirname(out), { recursive: true });
    if (skip(out, { force: FORCE, existsSync: fs.existsSync })) {
      console.log(`  [skip] ${p.kind} (exists)`);
      continue;
    }

    if (!p.prompt.trim()) {
      console.warn(
        `  [WARN] ${p.kind} — empty prompt (pre-gate placeholder), SKIPPED. ` +
          `Fill nearForegroundArt.types.${p.kind}.prompt (docs/art/prompts-road-props.md) ` +
          `before dispatching CI generation for this kind.`,
      );
      continue;
    }

    console.log(`  [gen]  ${p.kind}`);
    try {
      const { s, ground, opaque, effectiveSeed } = await generateOne(
        token,
        p.assembled,
        p.seed,
        p.width,
        p.height,
      );
      console.log(`  [seed] ${p.kind} seed=${effectiveSeed}${p.seed != null ? " (pinned)" : ""}`);
      fs.writeFileSync(out, s.toBuffer("image/png"));
      const v = cyanPreviewCanvas(s);
      fs.writeFileSync(out.replace(/\.png$/, "_cyan.png"), v.toBuffer("image/png"));
      console.log(
        `  [ok]   ${p.kind} (${p.width}x${p.height}, ground ${JSON.stringify(ground)}, ` +
          `opaque ${(opaque * 100).toFixed(1)}%)`,
      );
    } catch (e) {
      console.log(`  [fail] ${p.kind} — ${e.message} (will be generated in CI)`);
    }
    await sleep(2000);
  }

  console.log("\nDone.");
}

const isMain = process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href;
if (isMain) {
  main().catch((e) => {
    console.error("Fatal:", e.message);
    process.exit(1);
  });
}
