#!/usr/bin/env node
/**
 * ART GATE — hero wiring guard (ADR-0043 §4 Layer B). PERMANENT CI check that
 * a declared hero really reaches the diffusion model.
 *
 * Loads `references/approved/heroes.json`; an empty/absent registry PASSES
 * immediately (AC4 — no heroes ⇒ nothing to guard). For every declared hero it
 * fails (exit 1) when:
 *   - the family is DEFERRED (`levels`/`courier`, ADR-0043 §2) or unrecognised;
 *   - the entry shape is wrong, or its `approved` path is not the canonical
 *     `references/approved/<family>/<slug>.png`;
 *   - the frozen file is missing on disk;
 *   - `references/approved/HEROES.md` has no matching `REIGNING` entry for the
 *     family/slot/slug, or more than one `REIGNING` entry for the same slot;
 *   - an external-sourced entry (`source: "external"`, reserved for a future
 *     story — see HEROES.md) lacks a resolved `license` note;
 *   - THE LAST-MILE CHECK — the wired generator's own exported pure
 *     `planRequests({ repo, sha, registry })` does not yield, for every
 *     request belonging to that slot, a URL containing
 *     `image=${encodeURIComponent(heroRawUrl(approved, { repo, sha }))}`.
 *     `planRequests` is generated by the SAME `buildRequestUrl` the real
 *     generator uses at runtime, so this cannot silently diverge from what a
 *     real `node scripts/gen-*.mjs` run would actually send Pollinations —
 *     this is Bertrand's "hero declared but not used" guard, made permanent.
 *
 * Usage: node scripts/check-hero-wiring.mjs
 * Exit: 0 on an empty registry or full coherence; 1 on any violation.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import {
  loadHeroRegistry,
  canonicalApprovedPath,
  parseHeroesMd,
  resolveRepoSha,
  heroRawUrl,
  WIRED_FAMILIES,
  DEFERRED_FAMILIES,
  HEROES_MD_REL,
} from "./lib/heroes.mjs";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

// Which field of a planned request descriptor names the slot, per wired
// family/generator (vehicles: `type`, enemies: the flipbook `key`).
const GENERATOR_BY_FAMILY = {
  vehicles: { module: "./gen-vehicle-sprites.mjs", slotField: "type" },
  enemies: { module: "./gen-enemy-types.mjs", slotField: "key" },
};

function makeReport() {
  const errors = [];
  return {
    errors,
    error(pathStr, msg) {
      errors.push({ pathStr, msg });
    },
  };
}

function loadHeroesMdEntries() {
  const file = path.join(ROOT, HEROES_MD_REL);
  if (!fs.existsSync(file)) return [];
  return parseHeroesMd(fs.readFileSync(file, "utf8"));
}

async function loadPlanRequests(family) {
  const { module } = GENERATOR_BY_FAMILY[family];
  const mod = await import(module);
  if (typeof mod.planRequests !== "function") {
    throw new Error(`${module} does not export a pure planRequests() — cannot verify wiring`);
  }
  return mod.planRequests;
}

function checkRegistryEntries(registry, mdEntries, rep) {
  for (const [family, slots] of Object.entries(registry)) {
    if (DEFERRED_FAMILIES.includes(family)) {
      rep.error(
        family,
        `heroes.json declares a hero for the DEFERRED family "${family}" — levels/courier ` +
          `are not wired to consume heroes in v1 (ADR-0043 §2). Remove the machine entry; a ` +
          `human HEROES.md record is fine, a heroes.json entry is a hard error.`,
      );
      continue;
    }
    if (!WIRED_FAMILIES.includes(family)) {
      rep.error(
        family,
        `unrecognised family "${family}" in heroes.json (expected: ${WIRED_FAMILIES.join(", ")})`,
      );
      continue;
    }

    for (const [slot, entry] of Object.entries(slots ?? {})) {
      const p = `${family}.${slot}`;
      if (!entry || typeof entry.slug !== "string" || typeof entry.approved !== "string") {
        rep.error(
          p,
          `entry must be { slug: string, approved: string }, got ${JSON.stringify(entry)}`,
        );
        continue;
      }
      const { slug, approved } = entry;

      const expectedApproved = canonicalApprovedPath(family, slug);
      if (approved !== expectedApproved) {
        rep.error(
          p,
          `approved path "${approved}" does not equal the canonical "${expectedApproved}"`,
        );
      }

      const abs = path.join(ROOT, approved);
      if (!fs.existsSync(abs)) {
        rep.error(p, `frozen hero file missing on disk: ${approved}`);
      }

      const matching = mdEntries.filter(
        (e) => e.family === family && e.slot === slot && e.slug === slug,
      );
      if (matching.length === 0) {
        rep.error(p, `no HEROES.md entry found for "${family}/${slot} — ${slug}"`);
      } else if (matching.some((e) => e.status !== "REIGNING")) {
        rep.error(p, `HEROES.md entry for "${family}/${slot} — ${slug}" is not REIGNING`);
      }

      const reigningForSlot = mdEntries.filter(
        (e) => e.family === family && e.slot === slot && e.status === "REIGNING",
      );
      if (reigningForSlot.length > 1) {
        rep.error(
          p,
          `${reigningForSlot.length} REIGNING HEROES.md entries for "${family}/${slot}" — must be exactly one ` +
            `(${reigningForSlot.map((e) => e.slug).join(", ")})`,
        );
      }

      // License firewall — documented placeholder (ADR-0043 §2). No entry sets
      // `source` today (v1 only promotes internal heroes), so this never fires
      // yet; it guards the wiring the moment an external source is added.
      if (entry.source === "external" && !entry.license) {
        rep.error(
          p,
          `external-sourced hero missing a resolved "license" field (license firewall, ADR-0043 §2)`,
        );
      }
    }
  }
}

// Reverse scan (MINEUR-7) — the forward pass above (checkRegistryEntries +
// checkLastMileWiring) walks heroes.json → HEROES.md. This walks the OTHER
// direction: any HEROES.md REIGNING entry in a WIRED family/slot with NO
// matching heroes.json entry is a hero the human record claims is reigning
// but the machine registry (what generators and the guard above actually
// trust) never recorded — it can never reach `image=`. DEFERRED/unrecognised
// families are exempt (a human-only HEROES.md record is fine there, ADR-0043
// §2). Runs even when heroes.json is entirely empty.
function checkReverseWiring(registry, mdEntries, rep) {
  for (const e of mdEntries) {
    if (e.status !== "REIGNING") continue;
    if (!WIRED_FAMILIES.includes(e.family)) continue;
    const entry = registry?.[e.family]?.[e.slot];
    if (!entry || entry.slug !== e.slug) {
      rep.error(
        `${e.family}.${e.slot}`,
        `HEROES.md has a REIGNING entry for "${e.family}/${e.slot} — ${e.slug}" (a WIRED family) ` +
          `but heroes.json has no matching entry — declared but NOT threaded (reverse check).`,
      );
    }
  }
}

async function checkLastMileWiring(registry, rep) {
  const { repo, sha } = resolveRepoSha();

  for (const family of WIRED_FAMILIES) {
    const slots = registry[family];
    if (!slots || Object.keys(slots).length === 0) continue;

    let planRequests;
    try {
      planRequests = await loadPlanRequests(family);
    } catch (err) {
      rep.error(family, err.message);
      continue;
    }

    let planned;
    try {
      planned = planRequests({ repo, sha, registry });
    } catch (err) {
      rep.error(family, `planRequests() threw: ${err.message}`);
      continue;
    }

    const { slotField } = GENERATOR_BY_FAMILY[family];
    for (const [slot, entry] of Object.entries(slots)) {
      if (!entry?.approved) continue; // shape error already reported above
      const p = `${family}.${slot}`;
      const expectedImage = `image=${encodeURIComponent(heroRawUrl(entry.approved, { repo, sha }))}`;
      const requestsForSlot = planned.filter((req) => req[slotField] === slot);

      if (requestsForSlot.length === 0) {
        rep.error(
          p,
          `planRequests() produced NO request for slot "${slot}" — the declared hero can never reach ` +
            `image= for this generator (e.g. an enemy variant with no frame ≥2)`,
        );
        continue;
      }

      const allWired = requestsForSlot.every(
        (req) => typeof req.url === "string" && req.url.includes(expectedImage),
      );
      if (!allWired) {
        rep.error(
          p,
          `hero declared but NOT threaded into every generated request's image= — expected every request ` +
            `for "${slot}" to contain "${expectedImage}"`,
        );
      }
    }
  }
}

async function main() {
  const rep = makeReport();
  const registry = loadHeroRegistry(ROOT);
  const mdEntries = loadHeroesMdEntries();

  if (Object.keys(registry).length === 0) {
    console.log(
      "[check-hero-wiring] heroes.json is empty — nothing declared in the machine registry.",
    );
  } else {
    checkRegistryEntries(registry, mdEntries, rep);
    await checkLastMileWiring(registry, rep);
  }

  // Reverse scan last (MINEUR-7).
  checkReverseWiring(registry, mdEntries, rep);

  if (rep.errors.length > 0) {
    console.error(`[check-hero-wiring] FAILED — ${rep.errors.length} violation(s):`);
    for (const e of rep.errors) console.error(`  ✗ ${e.pathStr}\n      ${e.msg}`);
    process.exit(1);
  }

  console.log("[check-hero-wiring] PASSED — every declared hero is coherent and reaches image=.");
}

main().catch((e) => {
  console.error("Fatal:", e.message);
  process.exit(1);
});
