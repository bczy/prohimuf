// ---- main -------------------------------------------------------------------
const write = process.argv.includes("--write");
let adrs;
try {
  adrs = collectAdrs();
} catch (err) {
  console.error(`[adr-index] ERROR — ${err.message}`);
  process.exit(1);
}

const readmeNext = renderReadme(adrs);
const htmlNext = renderHtml(adrs);
const readmePath = path.join(ROOT, README);
const htmlPath = path.join(ROOT, HTML_OUT);

if (write) {
  fs.mkdirSync(path.dirname(htmlPath), { recursive: true });
  fs.writeFileSync(readmePath, readmeNext);
  fs.writeFileSync(htmlPath, htmlNext);
  console.log(`[adr-index] wrote ${README} and ${HTML_OUT} (${adrs.length} ADR).`);
  process.exit(0);
}

const stale = [];
if (fs.readFileSync(readmePath, "utf8") !== readmeNext) stale.push(README);
if (!fs.existsSync(htmlPath) || fs.readFileSync(htmlPath, "utf8") !== htmlNext)
  stale.push(HTML_OUT);
if (stale.length) {
  console.error(
    `[adr-index] STALE — ${stale.join(", ")} out of sync with docs/adr/.\n` +
      `Run: node scripts/gen-adr-index.mjs --write`,
  );
  process.exit(1);
}
console.log(`[adr-index] fresh — ${adrs.length} ADR, registry in sync.`);
process.exit(0);
