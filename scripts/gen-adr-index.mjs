#!/usr/bin/env node
/**
 * ADR REGISTRY GENERATOR + FRESHNESS GATE — keeps the ADR registry in sync with
 * the actual `docs/adr/NNNN-*.md` files, so a new ADR (even a `Proposed` draft)
 * shows up the moment its file lands, and a duplicate number can never pass
 * unnoticed again (that is how we ended up with two ADR-0020s).
 *
 * It owns two generated artifacts, both derived purely from the ADR files:
 *   - the `## Index` table in `docs/adr/README.md` (between INDEX markers)
 *   - the deployed registry page `public/adr/index.html`
 *     (served at https://bczy.github.io/prohimuf/adr/)
 *
 * Only fields that are honestly derivable from an ADR file are used: canonical
 * number (from the filename), title (from the H1), status (from the `Status:`
 * line — `Proposed` = a draft/brouillon) and a one-line summary (first sentence
 * of `## Context`). No implementation-status or hand-written blurbs live here:
 * those are point-in-time audits that would rot the instant they were frozen.
 *
 * Both generated files are prettier-ignored so this script has byte-exact
 * ownership of their formatting and `--check` can compare verbatim.
 *
 * Usage:
 *   node scripts/gen-adr-index.mjs           # verify (CI mode) — fail if stale
 *   node scripts/gen-adr-index.mjs --check   # same as above (explicit)
 *   node scripts/gen-adr-index.mjs --write   # regenerate the two artifacts
 * Exit: 0 fresh (or written); 1 stale, duplicate number, or malformed ADR.
 */
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");

const ADR_DIR = "docs/adr";
const README = path.join(ADR_DIR, "README.md");
const HTML_OUT = "public/adr/index.html";
const START =
  "<!-- ADR-INDEX:START — generated by scripts/gen-adr-index.mjs; do not edit by hand -->";
const END = "<!-- ADR-INDEX:END -->";

/** Collect and parse every ADR file, sorted by canonical (filename) number. */
function collectAdrs() {
  const files = fs
    .readdirSync(path.join(ROOT, ADR_DIR))
    .filter((f) => /^\d{4}-.+\.md$/.test(f))
    .sort();
  const adrs = files.map((file) => {
    const raw = fs.readFileSync(path.join(ROOT, ADR_DIR, file), "utf8");
    const num = file.slice(0, 4);
    const h1 = raw.match(/^#\s+(.+)$/m);
    if (!h1) throw new Error(`${file}: no H1 heading`);
    const title = h1[1].replace(/^\d{3,4}\s*[—–-]\s*/, "").trim();
    const statusLine = raw.match(/^\s*-\s*\*\*Status:\*\*\s*(.+?)\s*$/m);
    if (!statusLine) throw new Error(`${file}: no "- **Status:**" line`);
    return {
      num,
      file,
      title,
      status: normalizeStatus(statusLine[1]),
      summary: contextSummary(raw),
    };
  });
  assertNoDuplicates(adrs);
  return adrs;
}

/** Reduce a free-form Status line to a short, honest label. */
function normalizeStatus(rawStatus) {
  const plain = rawStatus.replace(/\[([^\]]+)\]\([^)]+\)/g, "$1"); // strip md links
  if (/^superseded/i.test(plain)) {
    const to = plain.match(/\b(\d{4})\b/);
    return to ? `Superseded by ${to[1]}` : "Superseded";
  }
  const base = /^proposed/i.test(plain)
    ? "Proposed"
    : /^accepted/i.test(plain)
      ? "Accepted"
      : plain.split(/[\s(—,:]/)[0];
  const notes = [];
  if (/amended/i.test(plain)) notes.push("amended");
  if (/partially superseded/i.test(plain)) {
    const to = plain.match(/superseded by[^0-9]*(\d{4})/i);
    notes.push(to ? `partially superseded by ${to[1]}` : "partially superseded");
  }
  return notes.length ? `${base} (${notes.join("; ")})` : base;
}

/** First sentence of the `## Context` section, flattened to plain-ish text. */
function contextSummary(raw) {
  const ctx = raw.match(/^##\s+Context\s*$([\s\S]*?)(?=^##\s)/m);
  if (!ctx) return "";
  const para = ctx[1].trim().split(/\n\s*\n/)[0] || "";
  const flat = para
    .replace(/\s+/g, " ")
    .replace(/\[([^\]]+)\]\([^)]+\)/g, "$1")
    .replace(/\*\*([^*]+)\*\*/g, "$1")
    .replace(/[*_]/g, "")
    .trim();
  const sentence = flat.match(/^.*?[.!?](?=\s|$)/)?.[0] ?? flat;
  return sentence.length > 200 ? sentence.slice(0, 197).replace(/\s+\S*$/, "") + "…" : sentence;
}

function assertNoDuplicates(adrs) {
  const byNum = new Map();
  for (const a of adrs) {
    if (!byNum.has(a.num)) byNum.set(a.num, []);
    byNum.get(a.num).push(a.file);
  }
  const dups = [...byNum].filter(([, files]) => files.length > 1);
  if (dups.length) {
    const lines = dups.map(([n, files]) => `  ${n}: ${files.join(", ")}`).join("\n");
    throw new Error(`duplicate ADR number(s) — renumber to the next free number:\n${lines}`);
  }
}

/** The Markdown index table (no padding — the file is prettier-ignored). */
function buildIndexTable(adrs) {
  const rows = adrs.map(
    (a) => `| [${a.num}](./${a.file}) | ${a.title.replace(/\|/g, "\\|")} | ${a.status} |`,
  );
  return ["| ADR | Title | Status |", "| --- | --- | --- |", ...rows].join("\n");
}

function renderReadme(adrs) {
  const current = fs.readFileSync(path.join(ROOT, README), "utf8");
  const s = current.indexOf(START);
  const e = current.indexOf(END);
  if (s === -1 || e === -1) throw new Error(`${README}: missing ADR-INDEX markers`);
  const block = `${START}\n\n${buildIndexTable(adrs)}\n\n${END}`;
  return current.slice(0, s) + block + current.slice(e + END.length);
}

function statusClass(status) {
  if (/^superseded/i.test(status)) return "superseded";
  if (/^proposed/i.test(status)) return "proposed";
  return "accepted";
}

